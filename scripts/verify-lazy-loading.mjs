/**
 * Lazy-loading verification — the property that makes ONE package safe.
 *
 * Collapsing five packages into one is only sound if a consumer can still leave
 * the heavy areas out of its entry chunk. This builds a real Vite application
 * that eagerly imports `contracts` and `companion` and lazily imports
 * `surfaces`, then asserts the surfaces code landed in a separate chunk.
 *
 * A synthetic weight fixture is injected into the built package for the
 * measurement, so the shipped package carries no dead payload.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, appendFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const pkg = resolve('.');
const MARKER = 'LAZY_PROBE_HEAVY_PAYLOAD';
const WEIGHT = 300_000; // a 300KB literal, standing in for editors and document tooling

// Inject the fixture into the BUILT output only. dist/ is regenerated by build.
appendFileSync(
  join(pkg, 'dist/surfaces/index.js'),
  `\nexport const __LAZY_PROBE = "${MARKER}${'x'.repeat(WEIGHT)}";\n`,
);

const dir = mkdtempSync(join(tmpdir(), 'lazy-probe-'));
mkdirSync(join(dir, 'src'), { recursive: true });
writeFileSync(join(dir, 'package.json'), JSON.stringify({
  name: 'lazy-probe', private: true, type: 'module', version: '0.0.0',
  dependencies: { '@motionmind/workspace': `file:${pkg}` },
}, null, 2));
writeFileSync(join(dir, 'vite.config.ts'), `import { defineConfig } from 'vite';\nexport default defineConfig({ build: { minify: false, target: 'es2022' } });\n`);
writeFileSync(join(dir, 'index.html'), `<!doctype html><html><body><div id="root"></div><script type="module" src="/src/main.ts"></script></body></html>`);
writeFileSync(join(dir, 'src/main.ts'), `
import { workspacePath } from '@motionmind/workspace/contracts';
import { COMPANION_MOUNT_RULE } from '@motionmind/workspace/companion';
document.getElementById('root')!.textContent = workspacePath('notebook') + COMPANION_MOUNT_RULE;
export async function openWorkspace() {
  const surfaces = await import('@motionmind/workspace/surfaces');
  return surfaces.LAZY_REQUIRED_AREAS.length;
}
(globalThis as Record<string, unknown>).openWorkspace = openWorkspace;
`);

execFileSync('npm', ['install', '--no-fund', '--no-audit', '--silent'], { cwd: dir, stdio: 'pipe' });
execFileSync('npm', ['install', '--no-save', '--no-fund', '--no-audit', '--silent', 'vite@5'], { cwd: dir, stdio: 'pipe' });
execFileSync('npx', ['vite', 'build'], { cwd: dir, stdio: 'pipe' });

const assets = join(dir, 'dist/assets');
let entry = null; let lazy = null;
for (const file of readdirSync(assets)) {
  const body = readFileSync(join(assets, file), 'utf8');
  const record = { file, bytes: body.length, heavy: body.includes(MARKER) };
  if (body.includes('COMPANION_MOUNT_RULE') || body.includes('/workspace/notebook')) entry = record;
  else if (record.heavy) lazy = record;
}

console.log(`  entry chunk : ${entry?.file} — ${entry?.bytes} bytes — contains heavy payload: ${entry?.heavy}`);
console.log(`  lazy chunk  : ${lazy?.file} — ${lazy?.bytes} bytes — contains heavy payload: ${lazy?.heavy}`);

// The assertion is both absolute and relative: the heavy area must be absent
// from the entry chunk, present in a separate chunk, and that chunk must
// actually carry the weight rather than a reference to it.
const ok =
  entry && lazy &&
  entry.heavy === false &&
  lazy.heavy === true &&
  lazy.bytes > WEIGHT * 0.9 &&
  entry.bytes < WEIGHT * 0.1;
console.log(ok
  ? '  PASS — the heavy area stayed out of the entry chunk; one package does not inflate first load'
  : '  FAIL — the heavy area leaked into the entry chunk');
process.exit(ok ? 0 : 1);
